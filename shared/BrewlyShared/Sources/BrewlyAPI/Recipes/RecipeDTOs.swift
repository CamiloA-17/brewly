import BrewlyCore
import Foundation

public struct RecipeStepDTO: Codable, Sendable, Equatable, Hashable {
    /// 1-based order of the step.
    public var position: Int
    public var kind: BrewStepKind
    /// Second at which the step starts.
    public var startS: Int
    /// Cumulative scale reading to reach during the step.
    public var waterTargetG: Double?
    public var instruction: String?

    public init(position: Int, kind: BrewStepKind, startS: Int, waterTargetG: Double? = nil, instruction: String? = nil) {
        self.position = position
        self.kind = kind
        self.startS = startS
        self.waterTargetG = waterTargetG
        self.instruction = instruction
    }
}

/// A step in a create/update request; its position is its index in the array.
public struct RecipeStepInput: Codable, Sendable, Equatable, Hashable {
    public var kind: BrewStepKind
    public var startS: Int
    public var waterTargetG: Double?
    public var instruction: String?

    public init(kind: BrewStepKind, startS: Int, waterTargetG: Double? = nil, instruction: String? = nil) {
        self.kind = kind
        self.startS = startS
        self.waterTargetG = waterTargetG
        self.instruction = instruction
    }
}

/// A full recipe (a preparation) with every brewing parameter.
public struct RecipeDTO: Codable, Sendable, Equatable, Hashable {
    public var id: UUID
    public var author: UserSummaryDTO
    public var bean: BeanSummaryDTO
    public var methodSlug: String
    public var forkedFromId: UUID?
    /// The original recipe of a remix; `nil` when it is gone or the viewer can't see it.
    public var forkedFrom: RecipeReferenceDTO?
    public var title: String
    public var description: String?
    public var doseG: Double
    public var waterG: Double?
    public var yieldG: Double?
    /// Generated by the database: brew water (or beverage) / dose.
    public var ratio: Double
    public var grindSize: GrindSize
    public var grinderSlug: String?
    public var grindSetting: String?
    public var grindMicrons: Int?
    public var waterTempC: Double?
    public var bloomWaterG: Double?
    public var bloomTimeS: Int?
    public var totalTimeS: Int?
    public var pressureBar: Double?
    public var filterType: FilterType?
    public var waterProfile: String?
    public var waterTdsPpm: Int?
    /// Cups the recipe makes.
    public var servings: Int?
    /// Ice in the carafe for iced brews; not part of the ratio.
    public var iceG: Double?
    /// Espresso-based drink the recipe makes.
    public var drinkType: DrinkType?
    public var milkG: Double?
    /// The exact brewer, e.g. "V60 02 ceramic".
    public var brewerDetail: String?
    public var coverURL: String?
    /// Average rating of the brews of this recipe that the viewer can see.
    public var averageRating: Double?
    /// Brews of this recipe that the viewer can see.
    public var brewCount: Int
    public var notes: String?
    public var flavorNoteSlugs: [String]
    public var steps: [RecipeStepDTO]
    public var visibility: Visibility
    /// How many people saved the recipe.
    public var saveCount: Int
    /// How many remixes were made from the recipe.
    public var forkCount: Int
    /// Whether the viewer saved the recipe.
    public var isSaved: Bool
    public var createdAt: Date
    public var updatedAt: Date

    public init(
        id: UUID,
        author: UserSummaryDTO,
        bean: BeanSummaryDTO,
        methodSlug: String,
        forkedFromId: UUID? = nil,
        forkedFrom: RecipeReferenceDTO? = nil,
        title: String,
        description: String? = nil,
        doseG: Double,
        waterG: Double? = nil,
        yieldG: Double? = nil,
        ratio: Double,
        grindSize: GrindSize,
        grinderSlug: String? = nil,
        grindSetting: String? = nil,
        grindMicrons: Int? = nil,
        waterTempC: Double? = nil,
        bloomWaterG: Double? = nil,
        bloomTimeS: Int? = nil,
        totalTimeS: Int? = nil,
        pressureBar: Double? = nil,
        filterType: FilterType? = nil,
        waterProfile: String? = nil,
        waterTdsPpm: Int? = nil,
        servings: Int? = nil,
        iceG: Double? = nil,
        drinkType: DrinkType? = nil,
        milkG: Double? = nil,
        brewerDetail: String? = nil,
        coverURL: String? = nil,
        averageRating: Double? = nil,
        brewCount: Int = 0,
        notes: String? = nil,
        flavorNoteSlugs: [String] = [],
        steps: [RecipeStepDTO] = [],
        visibility: Visibility = .public,
        saveCount: Int = 0,
        forkCount: Int = 0,
        isSaved: Bool = false,
        createdAt: Date,
        updatedAt: Date
    ) {
        self.id = id
        self.author = author
        self.bean = bean
        self.methodSlug = methodSlug
        self.forkedFromId = forkedFromId
        self.forkedFrom = forkedFrom
        self.title = title
        self.description = description
        self.doseG = doseG
        self.waterG = waterG
        self.yieldG = yieldG
        self.ratio = ratio
        self.grindSize = grindSize
        self.grinderSlug = grinderSlug
        self.grindSetting = grindSetting
        self.grindMicrons = grindMicrons
        self.waterTempC = waterTempC
        self.bloomWaterG = bloomWaterG
        self.bloomTimeS = bloomTimeS
        self.totalTimeS = totalTimeS
        self.pressureBar = pressureBar
        self.filterType = filterType
        self.waterProfile = waterProfile
        self.waterTdsPpm = waterTdsPpm
        self.servings = servings
        self.iceG = iceG
        self.drinkType = drinkType
        self.milkG = milkG
        self.brewerDetail = brewerDetail
        self.coverURL = coverURL
        self.averageRating = averageRating
        self.brewCount = brewCount
        self.notes = notes
        self.flavorNoteSlugs = flavorNoteSlugs
        self.steps = steps
        self.visibility = visibility
        self.saveCount = saveCount
        self.forkCount = forkCount
        self.isSaved = isSaved
        self.createdAt = createdAt
        self.updatedAt = updatedAt
    }
}

/// A link to another recipe, e.g. the original of a remix.
public struct RecipeReferenceDTO: Codable, Sendable, Equatable, Hashable {
    public var id: UUID
    public var title: String
    public var author: UserSummaryDTO

    public init(id: UUID, title: String, author: UserSummaryDTO) {
        self.id = id
        self.title = title
        self.author = author
    }
}

/// Response of `PUT` and `DELETE /recipes/{id}/save`.
public struct SaveStateDTO: Codable, Sendable, Equatable {
    public var isSaved: Bool
    public var saveCount: Int

    public init(isSaved: Bool, saveCount: Int) {
        self.isSaved = isSaved
        self.saveCount = saveCount
    }
}

